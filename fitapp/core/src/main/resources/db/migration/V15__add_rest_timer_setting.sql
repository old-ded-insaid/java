-- =============================================================================
-- V15: длительность отдыха между подходами в настройках пользователя.
--
-- Раньше таймер отдыха каждый раз начинался с «1:30» — это было захардкожено
-- в WorkoutController. Теперь значение живёт в app_settings, поэтому:
--   * по умолчанию 45 секунд (00:45) — для существующих и новых записей;
--   * пользователь меняет его спиннерами на экране тренировки, и при следующем
--     открытии тренировки таймер стартует с того же значения.
-- =============================================================================

-- DEFAULT 45 заполнит и уже существующие строки, и все будущие INSERT.
ALTER TABLE app_settings
    ADD COLUMN rest_timer_seconds INT NOT NULL DEFAULT 45;

-- Защита от опечаток: 0 — «отдых выключен», больше 99:59 — точно ошибка ввода.
ALTER TABLE app_settings
    ADD CONSTRAINT app_settings_rest_timer_range
        CHECK (rest_timer_seconds BETWEEN 0 AND 5999);

COMMENT ON COLUMN app_settings.rest_timer_seconds IS
    'Длительность отдыха между подходами, сек (по умолчанию 45 = 00:45)';
