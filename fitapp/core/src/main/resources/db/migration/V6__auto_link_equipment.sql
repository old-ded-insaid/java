-- =============================================================================
-- V6: авто-привязка инвентаря по ключевым словам в названии упражнения.
--
-- Зачем: в шаблонах и справочнике инвентарь был пустым — связи
-- exercise_equipment никто не создавал. Здесь мы один раз проходим по
-- названиям и привязываем подходящий инвентарь.
--
-- Как читать таблицу mapping:
--   keyword        — кусок названия упражнения (без учёта регистра)
--   equipment_name — точное имя инвентаря из V5
--   quantity       — количество по умолчанию
--
-- ON CONFLICT DO NOTHING делает миграцию безопасной при повторном запуске,
-- а DISTINCT убирает дубли, когда подходят несколько ключевых слов сразу
-- (например, «Жим гантелей лёжа на скамье» = гантели + скамья).
-- =============================================================================

WITH mapping(keyword, equipment_name, quantity) AS (
    VALUES
        -- гантели: даём два варианта, чтобы был выбор по весу
        ('гантел',             'Гантель 8 кг',        1),
        ('гантел',             'Гантель 6 кг',        1),

        -- скамья (в том числе «на скамье», «зашагивания на скамью»)
        ('скам',               'Скамья',              1),
        ('зашагив',            'Скамья',              1),

        -- резинки и петля-эспандер
        ('резин',              'Резинка черная',      1),
        ('резин',              'Резинка красная',     1),
        ('резин',              'Резинка зеленая',     1),
        ('резин',              'Петля (эспандер)',    1),
        ('pull-apart',         'Резинка черная',      1),
        ('pull-apart',         'Резинка красная',     1),
        ('монстер',            'Петля (эспандер)',    1),
        ('монстер',            'Резинка черная',      1),

        -- палка и весь блок ЛФК
        ('палк',               'Палка ЛФК',           1),
        ('лфк',                'Палка ЛФК',           1),

        -- мяч
        ('мяч',                'Мяч',                 1),
        ('обнимашк',           'Мяч',                 1),

        -- меч и щит (пока в базе таких упражнений нет — правила на будущее)
        ('меч',                'Длинный меч',         1),
        ('меч',                'Мягкий длинный меч',  1),
        ('щит',                'Деревянный щит',      1)
)
INSERT INTO exercise_equipment (exercise_id, equipment_id, quantity)
SELECT DISTINCT e.id, eq.id, m.quantity
FROM mapping m
JOIN exercises e  ON lower(e.name) LIKE '%' || lower(m.keyword) || '%'
JOIN equipment eq ON eq.name = m.equipment_name
ON CONFLICT (exercise_id, equipment_id) DO NOTHING;

COMMENT ON TABLE exercise_equipment IS
    'Инвентарь упражнения; связи частично проставлены миграцией V6 по названиям';
