-- =============================================================================
-- V9: правильные цвета резинок (по данным пользователя).
--
-- Что делает:
--   1. удаляет ВСЕ старые связи с резинками/петлями (V6/V7 привязали «чёрную»
--      ко всем упражнениям с резинкой);
--   2. добавляет точные виды инвентаря с весом (если таких записей ещё нет);
--   3. привязывает нужные цвета по названию упражнения.
--
-- Названия упражнений повторяются в разных тренировках (Pull-apart есть в А, В, Г),
-- поэтому привязка идёт по имени: если в разных тренировках нужны разные цвета,
-- упражнение получает оба варианта, и при выполнении любой тренировки видно оба.
--
-- Исключение из правила: «Тяга резины сидя» всегда получает 2 чёрные + жёлтую,
-- а её «быстрый» вариант («Тяга резины сидя в быстром темпе») — только зелёную.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. Чистим старые связи с резинками и петлями
-- -----------------------------------------------------------------------------
DELETE FROM exercise_equipment ee
USING equipment eq
WHERE eq.id = ee.equipment_id
  AND (eq.name ILIKE '%резин%'
       OR eq.name ILIKE '%петл%'
       OR eq.name ILIKE '%эспандер%');

-- -----------------------------------------------------------------------------
-- 2. Добавляем точные виды инвентаря с весом
--    ON CONFLICT DO NOTHING — безопасно, если запись уже есть
--    («Резинка желтая» и «Петля (эспандер)» пришли ещё из V5).
-- -----------------------------------------------------------------------------
INSERT INTO equipment (name, weight_grams) VALUES
    ('Резинка черная 22.7 кг', 22700),
    ('Резинка черная 27.2 кг', 27200),
    ('Резинка красная 9.1 кг',  9100),
    ('Резинка зеленая 13.6 кг', 13600),
    ('Резинка желтая',          NULL),
    ('Петля (эспандер)',        NULL)
ON CONFLICT (name) DO NOTHING;

-- -----------------------------------------------------------------------------
-- 3. Привязка по названиям упражнений
--    quantity = 1 для каждой строки.
-- -----------------------------------------------------------------------------
WITH mapping(keyword, equipment_name, quantity) AS (
    VALUES
        -- Тренировка А + В/Г: Pull-apart встречается с красной и зелёной
        ('Pull-apart',                        'Резинка красная 9.1 кг',  1),
        ('Pull-apart',                        'Резинка зеленая 13.6 кг', 1),

        -- Тренировка А: жим резины перед собой
        ('Жим резины перед собой',            'Резинка зеленая 13.6 кг', 1),

        -- Тренировки А, Б, Г: всегда две чёрные + жёлтая
        ('Тяга резины сидя',                  'Резинка черная 22.7 кг',  1),
        ('Тяга резины сидя',                  'Резинка черная 27.2 кг',  1),
        ('Тяга резины сидя',                  'Резинка желтая',          1),

        -- Тренировка В: «быстрый» вариант — только зелёная
        ('Тяга резины сидя в быстром темпе',  'Резинка зеленая 13.6 кг', 1),

        -- Тренировки Б и Г: петля
        ('Монстер-уолк',                      'Петля (эспандер)',        1),

        -- Тренировка В: цвет не указан — одна чёрная
        ('Быстрая тяга одной рукой без опоры', 'Резинка черная 22.7 кг', 1)
)
INSERT INTO exercise_equipment (exercise_id, equipment_id, quantity)
SELECT DISTINCT e.id, eq.id, m.quantity
FROM mapping m
JOIN exercises e  ON e.name ILIKE '%' || m.keyword || '%'
JOIN equipment eq ON eq.name = m.equipment_name
WHERE NOT (
        -- «Тяга резины сидя» не должна цеплять «быстрый» вариант:
        -- у него своё правило (зелёная резинка)
        m.keyword = 'Тяга резины сидя'
        AND e.name ILIKE '%в быстром темпе%'
      )
ON CONFLICT (exercise_id, equipment_id) DO NOTHING;
