-- =============================================================================
-- V12: жёлтая резинка — вес и в базе, и в названии.
--
-- Вес 4600 г уже проставлялся в V10/V11, но в названии его не было:
-- в списке инвентаря «Резинка желтая» выглядела как единственная без веса,
-- хотя у остальных написано «… 22.7 кг» и т.п.
--
-- Здесь:
--   1. гарантируем weight_grams = 4600;
--   2. переименовываем в «Резинка желтая 4.6 кг» (как у остальных полос);
--   3. правим текстовые снимки инвентаря в уже сохранённых тренировках.
-- =============================================================================

-- 1. Вес в граммах (на случай, если где-то остался NULL)
UPDATE equipment
SET weight_grams = 4600
WHERE name IN ('Резинка желтая', 'Резинка желтая 4.6 кг');

-- 2. Название с весом. NOT EXISTS — защита от конфликта уникального имени,
--    если запись с новым названием уже существует.
UPDATE equipment
SET name = 'Резинка желтая 4.6 кг'
WHERE name = 'Резинка желтая'
  AND NOT EXISTS (
        SELECT 1 FROM equipment WHERE name = 'Резинка желтая 4.6 кг'
      );

-- 3. Снимки в истории тренировок (текст) — чтобы старые тренировки
--    показывали то же название. NOT LIKE — защита от двойной замены.
UPDATE workout_exercises
SET equipment_snapshot = replace(
        equipment_snapshot,
        'Резинка желтая',
        'Резинка желтая 4.6 кг')
WHERE equipment_snapshot LIKE '%Резинка желтая%'
  AND equipment_snapshot NOT LIKE '%Резинка желтая 4.6 кг%';

-- 4. Проверка: у жёлтой должен быть вес и «кг» в названии
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM equipment
        WHERE name = 'Резинка желтая 4.6 кг'
          AND weight_grams = 4600
    ) THEN
        RAISE EXCEPTION 'V12: жёлтая резинка без веса или без веса в названии';
    END IF;
END $$;

COMMENT ON COLUMN equipment.weight_grams IS
    'Вес инвентаря в граммах; у гантелей не используется — вес задаётся в подходе';
